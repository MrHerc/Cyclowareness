def test_the_chain_builds_a_schema_that_matches_the_models(scratch):
    """`alembic check` on a freshly migrated database must find nothing.

    This is the property that lets the rest of the suite keep using
    `create_all()`: the models and the migrations describe the same schema, so a
    test that passes against the models passes against a migrated database.
    """
    scratch.upgrade("head")
    cfg = alembic_config()
    cfg.set_main_option("sqlalchemy.url", str(scratch.url))
    with scratch.begin() as conn:
        cfg.attributes["connection"] = conn
        command.check(cfg)  # raises AutogenerateDiffsDetected on drift


def test_no_table_references_one_that_does_not_exist_yet(tmp_path):
    """PostgreSQL validates a foreign key target at CREATE time. SQLite does not.

    So a baseline that creates `sandbox_jobs` (which references `loop_runs`)
    before `loop_runs` passes every local run and dies on the first PostgreSQL
    one with `relation "loop_runs" does not exist`. That is exactly what
    happened, and this test is why it cannot happen twice — it reads the
    PostgreSQL DDL that Alembic *renders*, so it catches the ordering without
    needing a PostgreSQL server.
    """
    sql = subprocess.run(
        [sys.executable, "-m", "alembic", "upgrade", "head", "--sql"],
        cwd=str(pathlib.Path(__file__).resolve().parents[1]),
        env={
            **os.environ,
            "DATABASE_URL": "postgresql+psycopg://u:p@localhost/db",
            "APP_ENV": "demo",
        },
        capture_output=True, text=True, check=True,
    ).stdout

    created: list[str] = []
    problems: list[str] = []
    for statement in sql.split(";"):
        match = re.search(r"CREATE TABLE (\w+)", statement)
        if not match:
            continue
        name = match.group(1)
        for target in re.findall(r"REFERENCES (\w+)", statement):
            if target != name and target not in created:
                problems.append(f"{name} REFERENCES {target} before it is created")
        created.append(name)

    assert created, "rendered no DDL at all — the check would pass vacuously"
    assert not problems, "; ".join(problems)


#: SQL that means different things on SQLite and PostgreSQL. Each entry is a
#: mistake this chain has actually made, or the direct sibling of one.
_DIALECT_TRAPS = (
    (
        r"\bMAX\s*\([^)]*,",
        "two-argument MAX is scalar on SQLite and an AGGREGATE on PostgreSQL — use CASE",
    ),
    (
        r"\bMIN\s*\([^)]*,",
        "two-argument MIN is scalar on SQLite and an AGGREGATE on PostgreSQL — use CASE",
    ),
    (
        r"\bGREATEST\s*\(|\bLEAST\s*\(",
        "GREATEST/LEAST do not exist on SQLite — use CASE",
    ),
    (
        r"server_default\s*=\s*[\"']\s*[\[{]",
        "a text server_default on a JSON column is refused by PostgreSQL — "
        "add nullable, backfill, then SET NOT NULL",
    ),
    (
        r"\bIFNULL\s*\(",
        "IFNULL is SQLite-only — use COALESCE",
    ),
    (
        r"\bdatetime\s*\(\s*'now'",
        "datetime('now') is SQLite-only — use CURRENT_TIMESTAMP or pass the value in",
    ),
)


def test_no_migration_uses_sql_that_means_something_different_on_postgresql():
    """The suite runs on SQLite; production runs on PostgreSQL.

    Every trap listed here has cost this chain a red build or would have: SQLite
    accepts the statement, PostgreSQL rejects it or — worse — reads it
    differently. Rendering the DDL is not enough to catch them, because
    `--sql` renders happily and only execution fails, so this reads the
    migration source instead.
    """
    versions = pathlib.Path(__file__).resolve().parents[1] / "migrations" / "versions"
    files = sorted(versions.glob("*.py"))
    assert files, "no migrations found — the check would pass vacuously"

    problems = []
    for path in files:
        source = path.read_text(encoding="utf-8")

        # Strip the MODULE DOCSTRING AND COMMENTS ONLY — never every triple-quoted
        # string. These traps are discussed in the very migrations that avoid
        # them, so an explanation must not read as an occurrence; but the SQL
        # lives inside `op.execute("""...""")`, so a blanket `"""..."""` strip
        # deletes exactly what this test exists to read. It did, and the test
        # passed on an injected `MAX(0.0, ...)` — vacuous and worse than absent.
        tree = ast.parse(source)
        body = source
        if (doc := ast.get_docstring(tree, clean=False)) is not None:
            body = body.replace(f'"""{doc}"""', "", 1)
        body = re.sub(r"^\s*#.*$", "", body, flags=re.MULTILINE)
        for pattern, why in _DIALECT_TRAPS:
            for match in re.finditer(pattern, body, re.IGNORECASE):
                line = body[: match.start()].count("\n") + 1
                problems.append(f"{path.name}:~{line}: {match.group(0)!r} — {why}")
    assert not problems, "\n".join(problems)


def test_the_downgrade_is_the_exact_reverse_of_the_upgrade(tmp_path):
    """Dropping a table still referenced by another fails on PostgreSQL.

    The upgrade order is checked above; this is its mirror. Getting it wrong
    breaks `alembic downgrade`, which is the only thing standing between a bad
    release and a restore from backup.
    """
    baseline = next(
        p for p in (pathlib.Path(__file__).resolve().parents[1] / "migrations" / "versions").glob("*.py")
        if "0001" in p.name
    )
    src = baseline.read_text(encoding="utf-8")
    up = src[src.index("def upgrade"):src.index("def downgrade")]
    down = src[src.index("def downgrade"):]
    created = re.findall(r"op\.create_table\('([a-z_]+)'", up)
    dropped = re.findall(r"op\.drop_table\('([a-z_]+)'", down)
    assert created, "no tables parsed — the check would pass vacuously"
    assert dropped == list(reversed(created))


def test_the_baseline_is_the_pre_integration_shape(scratch):
    """0001 must NOT already contain the integration.

    If it did, there would be no revision that adds those columns, and an
    existing database could never be repaired — which is the whole reason the
    baseline was split.
    """
    scratch.upgrade(BASELINE_REVISION)
    columns = scratch.columns("sandbox_jobs")
    assert not (INTEGRATION_COLUMNS & columns), "baseline already has the integration"
    assert MOVED_COLUMNS <= columns
    assert "sandbox_job_links" not in scratch.tables()


def test_upgrading_a_pre_integration_database_adds_the_nine_missing_columns(scratch):
    """The exact failure this migration exists for."""
    scratch.upgrade(BASELINE_REVISION)
    _seed_pre_integration(scratch)
    scratch.upgrade("head")

    columns = scratch.columns("sandbox_jobs")
    assert INTEGRATION_COLUMNS <= columns
    assert not (MOVED_COLUMNS & columns), "the moved columns should be gone from the job"

    with scratch.connect() as conn:
        row = conn.execute(text(
            "SELECT final_score, risk_level, tenant_id, verdict, mitre FROM sandbox_jobs WHERE id=1"
        )).one()
    # The row survived the rebuild, and the new columns carry their defaults
    # rather than NULL in a NOT NULL column.
    assert row.final_score == pytest.approx(70.0)
    assert row.risk_level == "high"
    assert row.tenant_id == "default"
    assert row.verdict == "{}"
    assert row.mitre == "[]"


def test_the_association_moves_to_the_link_table_rather_than_being_dropped(scratch):
    """`loop_run_id` and `submitted_by_user_id` leave the job but not the database.

    The engine may not carry a foreign key into `users` or `loop_runs` — the
    standalone product has neither table — so the portal keeps the association
    on its own side of the seam. Losing it would silently orphan every job the
    awareness loop had raised.
    """
    scratch.upgrade(BASELINE_REVISION)
    _seed_pre_integration(scratch)
    scratch.upgrade("head")

    with scratch.connect() as conn:
        link = conn.execute(text(
            "SELECT job_id, loop_run_id, submitted_by_user_id FROM sandbox_job_links"
        )).one()
    assert (link.job_id, link.loop_run_id, link.submitted_by_user_id) == (1, 3, 7)


