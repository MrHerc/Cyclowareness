"""Migrations, and the upgrade path that used to lose columns silently.

Every test here runs against its OWN throwaway database, built with a second
engine — never the session-wide one the rest of the suite shares. Running a
migration against that would rebuild the schema out from under every other test.

The scenario these exist for: `create_all()` CREATES a table it has never seen
and does nothing to one it has. Swapping in the vendored sandbox engine added
nine columns to `sandbox_jobs`, so on any existing database the release reported
success and left them missing — `/api/health` answering 200 while every sandbox
query raised `no such column: sandbox_jobs.tenant_id`.
"""
from __future__ import annotations

import ast
import os
import pathlib
import re
import subprocess
import sys
from datetime import datetime, timezone

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect, text

from app.database import (
    _ADOPTION_LADDER,
    BASELINE_REVISION,
    SANDBOX_ENGINE_REVISION,
    UnadoptableDatabase,
    _legacy_stamp_target,
    alembic_config,
)

#: The nine columns the sandbox engine integration added. If a future revision
#: adds more, this list is not what needs updating — the adoption ladder in
#: app/database.py is.
INTEGRATION_COLUMNS = {
    "tenant_id", "submitted_by", "dynamic", "sample_deleted_at", "impact",
    "verdict", "mitre", "first_completed_at", "engine_manifest",
}

#: What the pre-integration table carried instead, and what moved to
#: `sandbox_job_links` rather than being deleted.
MOVED_COLUMNS = {"loop_run_id", "submitted_by_user_id"}


@pytest.fixture
def scratch(tmp_path):
    """A private database and an Alembic config pointed at it."""
    url = f"sqlite:///{tmp_path / 'scratch.db'}"
    eng = create_engine(url)

    def config_at() -> Config:
        cfg = alembic_config()
        cfg.set_main_option("sqlalchemy.url", url)
        return cfg

    def upgrade(target: str) -> None:
        cfg = config_at()
        with eng.begin() as conn:
            cfg.attributes["connection"] = conn
            command.upgrade(cfg, target)

    def stamp(target: str) -> None:
        cfg = config_at()
        with eng.begin() as conn:
            cfg.attributes["connection"] = conn
            command.stamp(cfg, target)

    def columns(table: str) -> set[str]:
        with eng.connect() as conn:
            return {c["name"] for c in inspect(conn).get_columns(table)}

    def tables() -> set[str]:
        with eng.connect() as conn:
            return set(inspect(conn).get_table_names())

    eng.upgrade = upgrade          # type: ignore[attr-defined]
    eng.stamp = stamp              # type: ignore[attr-defined]
    eng.columns = columns          # type: ignore[attr-defined]
    eng.tables = tables            # type: ignore[attr-defined]
    yield eng
    eng.dispose()


